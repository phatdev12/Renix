import pathlib, sys
from playwright.sync_api import sync_playwright
url = pathlib.Path('D:/Nix/index.html').as_uri()
out = pathlib.Path(sys.argv[1]); out.mkdir(exist_ok=True)
with sync_playwright() as p:
    b = p.chromium.launch(channel='msedge', headless=True)
    pg = b.new_page(viewport={'width': 1280, 'height': 1000})
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.goto(url + '#/bank/1943'); pg.wait_for_timeout(700)
    # order question 1: click chips in the correct order using the answer key
    key = pg.evaluate("BANK.find(q=>q.id==='1943').parts[0].questions[0]")
    card = pg.locator('.qcard').nth(0)
    for i in key['ans']:
        card.locator('.chips-pool .wchip').nth(i).click()
    card.locator('button:has-text("Kiểm tra")').click()
    print('order q1 ->', card.locator('.explain').inner_text()[:120].replace('\n', ' | '))
    # order question 2: wrong order
    card2 = pg.locator('.qcard').nth(1)
    n = len(pg.evaluate("BANK.find(q=>q.id==='1943').parts[0].questions[1].chips"))
    for i in range(n): card2.locator('.chips-pool .wchip').nth(i).click()
    card2.locator('button:has-text("Kiểm tra")').click()
    print('order q2 (as-is) ->', card2.locator('.explain').inner_text()[:100].replace('\n', ' | '))
    # matching question (part 1)
    mq = pg.evaluate("BANK.find(q=>q.id==='1943').parts[1].questions[0]")
    card3 = pg.locator('.qcard').nth(3)
    for si, a in enumerate(mq['ans']):
        card3.locator('select').nth(si).select_option(str(a))
    card3.locator('button:has-text("Kiểm tra")').click()
    print('matching ->', card3.locator('.explain').inner_text()[:100].replace('\n', ' | '))
    pg.screenshot(path=str(out / 'bank_order.png'), full_page=True)
    # blanks with free text (2154 part0 q1)
    pg.evaluate("location.hash='#/bank/2154'"); pg.wait_for_timeout(700)
    bq = pg.evaluate("BANK.find(q=>q.id==='2154').parts[0].questions[0]")
    c = pg.locator('.qcard').nth(0)
    ans = bq['ans']['1']; ans = ans[0] if isinstance(ans, list) else ans
    c.locator('input').first.fill(ans)
    c.locator('button:has-text("Kiểm tra")').click()
    print('blank free ->', bq['ans'], c.locator('.explain').inner_text()[:90].replace('\n', ' | '))
    # romaji typing into a blank
    c2 = pg.locator('.qcard').nth(1)
    c2.locator('input').first.click(); pg.keyboard.type('utai')
    print('romaji typed ->', c2.locator('input').first.input_value())
    pg.screenshot(path=str(out / 'bank_blanks.png'))
    # single choice wrong then explanation (1880 q1)
    pg.evaluate("location.hash='#/bank/1880'"); pg.wait_for_timeout(700)
    c = pg.locator('.qcard').nth(0)
    c.locator('.opt').nth(0).click(); c.locator('button:has-text("Kiểm tra")').click()
    print('single ->', c.locator('.explain').inner_text()[:140].replace('\n', ' | '))
    # LMS override question 2026/1/3
    pg.evaluate("location.hash='#/bank/2026'"); pg.wait_for_timeout(700)
    idx = pg.evaluate("(() => { let n=0; const qz=BANK.find(q=>q.id==='2026'); for (const p of qz.parts) for (const q of p.questions) { if (q.key==='2026/1/3') return n; n++; } })()")
    c = pg.locator('.qcard').nth(idx)
    c.locator('.opt').nth(3).click(); c.locator('button:has-text("Kiểm tra")').click()
    print('lms override ->', c.inner_text()[-330:].replace('\n', ' | '))
    c.scroll_into_view_if_needed(); pg.screenshot(path=str(out / 'bank_lms.png'))
    # test mode + submit on a dragtext quiz (1920)
    pg.evaluate("localStorage.setItem('nix.bankUi', JSON.stringify({mode:'test'})); location.hash='#/bank/1920'"); pg.wait_for_timeout(800)
    pg.once('dialog', lambda d: d.accept())
    pg.locator('button:has-text("Nộp bài")').first.click(); pg.wait_for_timeout(500)
    print('submit modal ->', pg.locator('.modal').inner_text()[:80].replace('\n', ' | '))
    print('errors:', errs)
    b.close()
